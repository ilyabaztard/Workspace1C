using System;

namespace Workspace1C.Services;

/// <summary>
/// Глобальная горячая клавиша «показать главное окно» (issue #82), работающая независимо
/// от активного приложения — из системного трея, свёрнутого или находящегося на заднем
/// плане окна. Платформенная реализация регистрирует нативный хук (RegisterHotKey на
/// Windows, XGrabKey + X11-цикл на Linux) и в момент нажатия вызывает
/// <see cref="HotkeyPressed"/>. Логика действия (восстановить/активировать окно) —
/// платформонезависимая, живёт у вызывающего (главное окно), что позволяет
/// юнит-тестировать контракт без реального UI.
/// </summary>
public interface IGlobalHotkeyService : IDisposable
{
    /// <summary>Зарегистрированная комбинация (пусто — не зарегистрирована).</summary>
    string? RegisteredGesture { get; }

    /// <summary>
    /// Перерегистрирует глобальную клавишу. Пустые/null значения, невалидные комбинации
    /// и занятия клавиши другим приложением отключают регистрацию (настройка сохраняется,
    /// но не срабатывает) — приложение продолжает работать.
    /// </summary>
    void SetGesture(string? gesture);

    /// <summary>Вызывается при нажатии глобальной клавиши; при Dispose сбрасывается в null.</summary>
    Action? HotkeyPressed { get; set; }
}